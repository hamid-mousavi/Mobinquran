import { UserIntent } from './types';

// الگوهای تشخیص احوال‌پرسی و گفت‌وگوی عادی
const CASUAL_PATTERNS = [
  /^(سلام|درود|سلام علیکم|سلام بر شما|سلامتی|خوبی|چطوری|درود بر شما|روز بخیر|صبح بخیر|عصر بخیر|شب بخیر|وقت بخیر|یا علی|یا حق|خسته نباشید|ممنون|تشکر|متشکرم|مرسی|دمت گرم|سپاس|قربانت|فدات|ارادت|خداحافظ|فعلا|بای|هی|الو)[\s!.,،؟?]*$/i,
  /^(تو کی هستی|اسمت چیه|خودتو معرفی کن|چیکار می\s*تونی بکنی|چه کمکی می\s*تونی بکنی|سازنده تو کیه|هوش مصنوعی هستی|سلام عزیزم|سلام دوست من)[\s!.,،؟?]*$/i,
];

// الگوهای تشخیص اطلاعات روز و اخبار
const CURRENT_INFO_PATTERNS = [
  /امروز\s*(چندم|چند شنبه|چه روزی|تاریخ|مناسبت)/i,
  /(اخبار|خبرهای|رویدادهای|اتفاقات|وضعیت)\s*(امروز|اخیر|روز|کشور|جهان)/i,
  /(قیمت|نرخ)\s*(دلار|ارز|طلا|سکه|بنزین)/i,
  /(آب و هوا|پیش\s*بینی هوا|دمای هوا)/i,
  /(جدیدترین|آخرین)\s*(دستاوردهای|اخبار|اکتشافات)/i,
];

// الگوهای قرآنی و معارفی
const QURAN_KEYWORDS = [
  'قرآن', 'آیه', 'سوره', 'تفسیر', 'حدیث', 'روایت', 'معارف', 'خدا', 'پروردگار',
  'صبر', 'توکل', 'رزق', 'روزی', 'دعا', 'استغفار', 'نماز', 'روزه', 'زکات', 'حج',
  'معاد', 'قیامت', 'بهشت', 'جهنم', 'برزخ', 'روح', 'تقوا', 'اخلاق', 'عدالت',
  'احسان', 'والدین', 'پدر', 'مادر', 'ظلم', 'حرام', 'حلال', 'مومن', 'کافر', 'منافق',
  'پیامبر', 'رسول', 'امام', 'اهل بیت', 'توبه', 'شکر', 'امید', 'ناامیدی', 'یاس',
  'هدایت', 'گمراهی', 'فرشته', 'شیطان', 'وسوسه', 'آرامش', 'اضطراب', 'عفو', 'بخشش',
  'حجاب', 'عفت', 'جهاد', 'شهادت', 'قضا و قدر', 'حق الناس', 'امانت', 'صداقت',
];

export function detectIntent(question: string, hasCurrentVerseContext = false): UserIntent {
  const q = question.trim();
  if (!q) return 'casual_chat';

  // اگر کاربر روی آیه خاصی در حال قرائت است و سوالی می‌پرسد
  if (hasCurrentVerseContext && !CASUAL_PATTERNS.some((p) => p.test(q))) {
    return 'quran_inquiry';
  }

  // ۱. بررسی گفت‌وگوی عادی و احوال‌پرسی
  if (CASUAL_PATTERNS.some((p) => p.test(q))) {
    return 'casual_chat';
  }

  // ۲. بررسی بررسی ترکیبی (آیا هم موضوع روز است و هم پیوند به دین و قرآن دارد؟)
  const isCurrent = CURRENT_INFO_PATTERNS.some((p) => p.test(q));
  const hasQuranKeywords = QURAN_KEYWORDS.some((kw) => q.includes(kw));

  if (isCurrent && hasQuranKeywords) {
    return 'hybrid';
  }

  if (isCurrent) {
    return 'current_info';
  }

  // ۳. بررسی سوالات دینی، قرآنی یا تدبری
  if (hasQuranKeywords) {
    return 'quran_inquiry';
  }

  // سوالاتی که درباره مفاهیم زندگی یا اخلاق انسانی هستند (مانند: چرا غمگینم؟، راه شاد زیستن، مواجهه با شکست)
  // این سوالات باید با معارف قرآن پاسخ داده شوند
  return 'quran_inquiry';
}
